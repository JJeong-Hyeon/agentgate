create table if not exists agent_memories (
    id bigint generated by default as identity primary key,
    agent_id varchar(255) not null,
    content varchar(4000) not null,
    source varchar(20) not null check (source in ('AGENT', 'USER')),
    execution_id varchar(255),
    created_by varchar(255),
    embedding_model varchar(200),
    created_at timestamp(6) with time zone not null default now()
);

create index if not exists agent_memories_agent_created_idx on agent_memories (agent_id, created_at desc);

-- Optional extensions: pgvector enables semantic search (an "embedding" column), pg_trgm speeds up keyword search.
-- Without them (not installed, or no privilege to create them) memories still work with keyword search only.
do $$
begin
    if exists (select 1 from pg_available_extensions where name = 'pg_trgm') then
        begin
            create extension if not exists pg_trgm;
            create index if not exists agent_memories_content_trgm_idx on agent_memories using gin (content gin_trgm_ops);
        exception when insufficient_privilege then
            raise notice 'pg_trgm not created: %', sqlerrm;
        end;
    end if;
    if exists (select 1 from pg_available_extensions where name = 'vector') then
        begin
            create extension if not exists vector;
            -- No fixed dimension: rows are only compared with vectors from the same embedding_model.
            alter table agent_memories add column if not exists embedding vector;
        exception when insufficient_privilege then
            raise notice 'vector not created: %', sqlerrm;
        end;
    end if;
end
$$;
